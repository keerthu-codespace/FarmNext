export const getTranslation = (key: string, lang: Language, fallback?: string): string => {
  const langDict = translations[lang];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  const enDict = translations['en'];
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return fallback || key;
};
